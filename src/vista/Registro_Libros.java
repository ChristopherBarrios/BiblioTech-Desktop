    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        String isbn = txtIsbn.getText().trim();
        String titulo = txtTitulo.getText().trim();
        String editorial = txtEditorial.getText().trim();
        String categoria = txtCategoria.getText().trim();

        if (isbn.isEmpty() || titulo.isEmpty() || editorial.isEmpty() || categoria.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, completa todos los campos.");
            return;
        }
        if (isbn.length() > 50 || titulo.length() > 50
                || editorial.length() > 50 || categoria.length() > 50) {
            JOptionPane.showMessageDialog(this, "Cada campo admite máximo 50 caracteres.");
            return;
        }

        ClaseLibro nuevo = new ClaseLibro();
        nuevo.setIsbn(isbn);
        nuevo.setTitulo(titulo);
        nuevo.setEditorial(editorial);
        nuevo.setCategoria(categoria);

        Crud_Libros proceso = new Crud_Libros();
        if (proceso.insertar(nuevo)) {
            txtIsbn.setText("");
            txtTitulo.setText("");
            txtEditorial.setText("");
            txtCategoria.setText("");
            txtIsbn.requestFocus();
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

