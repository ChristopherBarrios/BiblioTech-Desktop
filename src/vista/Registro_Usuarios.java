    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText().trim();
        String telTexto = txtTelefono.getText().trim();
        String fechaTexto = txtFecha_nac.getText().trim();

        if (nombre.isEmpty() || telTexto.isEmpty() || fechaTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, completa todos los campos.");
            return;
        }

        try {
            
            long telefono = Long.parseLong(telTexto);
            Date fechaNac = Date.valueOf(fechaTexto);

            Usuario nuevo = new Usuario(nombre, telefono, fechaNac);   // ← se crea el objeto
            Crud operaciones = new Crud();
            operaciones.insertar(nuevo);  

            txtNombre.setText("");
            txtTelefono.setText("");
            txtFecha_nac.setText("");
            txtNombre.requestFocus();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El teléfono debe contener solo números.");
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Usa AAAA-MM-DD (ej. 2005-03-14).");
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

