    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
        String isbn = txtIsbn.getText().trim();
    String titulo = txtTitulo.getText().trim();
    String editorial = txtEditorial.getText().trim();
    String categoria = txtCategoria.getText().trim();

    if (isbn.isEmpty() || titulo.isEmpty() || editorial.isEmpty() || categoria.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, completa todos los campos.");
        return;
    }
    if (isbn.length() > 50 || titulo.length() > 50
            || editorial.length() > 50 || categoria.length() > 50) {
        JOptionPane.showMessageDialog(this, "Cada campo admite máximo 50 caracteres.");
        return;
    }

    ClaseLibro obj = new ClaseLibro();
    obj.setIdLibro(idLibro);
    obj.setIsbn(isbn);
    obj.setTitulo(titulo);
    obj.setEditorial(editorial);
    obj.setCategoria(categoria);

    if (new Crud_Libros().modificar(obj)) {
        this.dispose();
    }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int confirmar = JOptionPane.showConfirmDialog(this,
            "¿Eliminar este libro?\nTambién se borrarán sus préstamos y multas.",
            "Confirmar", JOptionPane.YES_NO_OPTION);
        
        if (confirmar == JOptionPane.YES_OPTION) {
            if (new Crud_Libros().eliminar(idLibro)) {
                this.dispose();
            }
}
    }//GEN-LAST:event_btnEliminarActionPerformed

