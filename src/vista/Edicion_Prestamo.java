    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
    String libro = txtLibro.getText();
    String fprestamo = txtPrestamo.getText();
    String fDevolucion = txtDevolucion.getText();
    
    if(libro.isEmpty() || fprestamo.isEmpty() || fDevolucion.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, completa todos los campos");
        return;
    }
    ClasePrestamos obj = new ClasePrestamos();
    obj.setIdPide(Integer.parseInt(lblID.getText()));
    obj.setLibro(libro);
    obj.setFechaPrestamo(fprestamo);
    obj.setFechaDevolucion(fDevolucion);
    
    Crud_Prestamo proceso = new Crud_Prestamo();
    if(proceso.modificar(obj)){
    Consulta_Prestamo con = new Consulta_Prestamo();
    con.setVisible(true);
    this.dispose();
      
    
    }
    

    }//GEN-LAST:event_btnActualizarActionPerformed

